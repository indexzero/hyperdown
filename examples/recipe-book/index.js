// The AutoVault-LD flagship example: FOUR AGENT WRITERS co-author a recipe
// book as a knowledge graph, from scratch, on ONE shared multi-writer
// vault — then a human operator dumps the result of the session as a
// readable Markdown vault and a Turtle export (the committed out/ tree).
//
//   node examples/recipe-book            (from the repo root, after pnpm install)
//
// The cast (each agent is its own vault peer with its own writer core):
//   Nova  — ontology architect (vault creator, genesis indexer)
//   Basil — soups & starters
//   Clove — bakes & breads
//   Dill  — mains, the pantry, and end-of-session editorial duty
//
// What it demonstrates, in order:
//   1. governance   — Nova admits the three agents as writers (logged ops, §8.0)
//   2. ontology     — the schema is ORDINARY CONTENT in the same log
//                     (DefineScope/DefineTerm: Recipe, Ingredient,
//                     hasIngredient, prepTime, ...)
//   3. concurrency  — Basil/Clove/Dill write recipes OFFLINE and in
//                     parallel: OR-set fields union across writers,
//                     LWW registers pick one deterministic winner and
//                     flag the overwrite (§5.4), wiki-links to notes that
//                     do not exist yet mint IRIs and flag dangling (§7)
//   4. conflict     — two agents write the same prose body from the same
//                     base; the system keeps BOTH revisions and flags the
//                     conflict (§6); Dill resolves it with a merge op
//   5. faces        — materialize() writes the Obsidian-readable vault and
//                     exportTurtle() writes schema.ttl/data.ttl (§9, §10)
//
// Determinism: writer key pairs are derived from fixed seeds and every
// concurrent phase starts from a fully converged barrier, so the final
// view — and therefore every byte under out/ — is identical on every run
// (I9; asserted by test/example-recipe-book.test.js). Do not hand-edit
// out/: it is regenerated by this script.
import { createHash } from 'node:crypto'
import { mkdir } from 'node:fs/promises'
import { join, dirname, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import crypto from 'hypercore-crypto'
import b4a from 'b4a'
import { Vault } from '@autovault-ld/store'
import { materialize, exportTurtle } from '@autovault-ld/faces'
import { keyspace as K, revHash } from '@autovault-ld/core'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = join(HERE, '..', '..')

// Committed, human-readable output (override for tests).
const OUT = process.env.RECIPE_BOOK_OUT ? resolve(process.env.RECIPE_BOOK_OUT) : join(HERE, 'out')
// Per-run vault storage scratch (never reused, never cleaned up).
const STORAGE = process.env.RECIPE_BOOK_STORAGE
  ? resolve(process.env.RECIPE_BOOK_STORAGE)
  : join(REPO, 'sslop', '015', 'tmp', 'recipe-book', `run-${process.pid}-${Date.now()}`)

const seed = (name) => createHash('sha256').update(`autovault-ld/recipe-book/${name}`).digest()
const say = (who, msg) => console.log(`[${who.padEnd(5)}] ${msg}`)
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function until(fn, ms = 30000, step = 50) {
  const t0 = Date.now()
  for (;;) {
    if (await fn()) return true
    if (Date.now() - t0 >= ms) return false
    await sleep(step)
  }
}

/** Direct replication stream pair; returns an unpair(). */
function pairVaults(a, b) {
  const s1 = a.replicate(true)
  const s2 = b.replicate(false)
  s1.on('error', () => {})
  s2.on('error', () => {})
  s1.pipe(s2).pipe(s1)
  return () => {
    s1.destroy()
    s2.destroy()
  }
}

/** Full-mesh replication among all peers; returns a teardown(). */
function mesh(vaults) {
  const unpairs = []
  for (let i = 0; i < vaults.length; i++) {
    for (let j = i + 1; j < vaults.length; j++) unpairs.push(pairVaults(vaults[i], vaults[j]))
  }
  return () => unpairs.forEach((u) => u())
}

/** Barrier: wait until every peer holds the identical view (I2). */
async function converge(vaults) {
  const ok = await until(async () => {
    const hashes = []
    for (const v of vaults) {
      await v.update()
      hashes.push(await v.hash())
    }
    return hashes.every((h) => h === hashes[0])
  })
  if (!ok) throw new Error('peers failed to converge')
}

async function main() {
  await mkdir(STORAGE, { recursive: true })
  console.log('=== recipe-book: four agents, one shared vault ===\n')

  // ---- session setup: one vault, four writers ------------------------------
  const nova = await Vault.init(join(STORAGE, 'nova'), { keyPair: crypto.keyPair(seed('nova')) })
  const basil = await Vault.join(join(STORAGE, 'basil'), nova.key, { keyPair: crypto.keyPair(seed('basil')) })
  const clove = await Vault.join(join(STORAGE, 'clove'), nova.key, { keyPair: crypto.keyPair(seed('clove')) })
  const dill = await Vault.join(join(STORAGE, 'dill'), nova.key, { keyPair: crypto.keyPair(seed('dill')) })
  const agents = [nova, basil, clove, dill]

  say('nova', `created the vault (key ${nova.keyHex.slice(0, 16)}…); Nova is the genesis indexer`)
  let offline = mesh(agents)
  for (const [name, v] of [['basil', basil], ['clove', clove], ['dill', dill]]) {
    await nova.addWriter(v.localKey, { indexer: false })
    say('nova', `admitted ${name} as a writer (AddWriter op, ${b4a.toString(v.localKey, 'hex').slice(0, 16)}…)`)
  }
  for (const v of [basil, clove, dill]) {
    if (!(await until(async () => { await v.update(); return v.writable }))) {
      throw new Error('agent never became writable')
    }
  }

  // ---- phase 1: Nova defines the ontology (schema is content in the log) ---
  say('nova', 'defining the culinary ontology — DefineScope/DefineTerm are ordinary logged ops')
  await nova.defineScope('culinary', 'https://recipes.example/culinary#', 'cul')
  await nova.defineTerm('culinary', 'type', '@type') // keyword aliases (vault-ld §4.3)
  await nova.defineTerm('culinary', 'id', '@id')
  await nova.defineTerm('culinary', 'title', { '@id': 'cul:title' })
  await nova.defineTerm('culinary', 'comment', { '@id': 'rdfs:comment' })
  await nova.defineTerm('culinary', 'cuisine', { '@id': 'cul:cuisine' })
  await nova.defineTerm('culinary', 'servings', { '@id': 'cul:servings' })
  await nova.defineTerm('culinary', 'prepTime', { '@id': 'cul:prepTime' }) // minutes
  await nova.defineTerm('culinary', 'difficulty', { '@id': 'cul:difficulty' })
  await nova.defineTerm('culinary', 'hasIngredient', { '@id': 'cul:hasIngredient', '@container': '@set' })
  await nova.defineTerm('culinary', 'pairsWith', { '@id': 'cul:pairsWith', '@container': '@set' })
  await nova.defineTerm('culinary', 'domain', { '@id': 'rdfs:domain', '@type': '@id' })
  await nova.defineTerm('culinary', 'range', { '@id': 'rdfs:range', '@type': '@id' })

  // Schema notes: classes and the object property, placed per vault-ld §5.1.
  await nova.addMember('Recipe', 'type', 'owl:Class')
  await nova.setField('Recipe', 'comment', 'A dish somebody can actually cook.')
  await nova.append('set-path', { s: 'Recipe', path: 'Ontologies/culinary/Classes/Recipe', scope: 'culinary' })
  await nova.addMember('Ingredient', 'type', 'owl:Class')
  await nova.setField('Ingredient', 'comment', 'Something a recipe is made of.')
  await nova.append('set-path', { s: 'Ingredient', path: 'Ontologies/culinary/Classes/Ingredient', scope: 'culinary' })
  await nova.addMember('hasIngredient', 'type', 'owl:ObjectProperty')
  await nova.setField('hasIngredient', 'domain', 'cul:Recipe')
  await nova.setField('hasIngredient', 'range', 'cul:Ingredient')
  await nova.append('set-path', { s: 'hasIngredient', path: 'Ontologies/culinary/Properties/hasIngredient', scope: 'culinary' })

  // Basil posts a first draft of the soup body while everyone is still
  // connected: this converged revision is the SHARED BASE the §6 conflict
  // below needs (a null base is "no base cited" and never conflicts — only
  // two revisions citing the same non-null base are true concurrency).
  say('basil', 'posting a first draft of the "Tomato Soup" body — the shared base for what follows')
  const draftBody = 'Simmer tomatoes. Season. Serve.'
  await basil.setBody('Tomato Soup', null, draftBody)
  const draft = revHash(null, draftBody)

  await converge(agents)
  say('all', 'barrier: ontology replicated; every peer holds a bit-identical view (I2)\n')

  // ---- phase 2: the agents go OFFLINE and write concurrently ---------------
  offline() // tear down replication: everything below is truly concurrent
  console.log('--- the agents disconnect and write in parallel ---')

  // Basil drafts the soup. [[Saffron]] does not exist anywhere yet: the ref
  // mints an IRI and flags dangling (§7).
  say('basil', 'drafting "Tomato Soup" (refs [[Tomato]], [[Garlic]], [[Olive Oil]], [[Saffron]])')
  await basil.addMember('Tomato Soup', 'type', { ref: 'Recipe' })
  await basil.setField('Tomato Soup', 'title', 'Rustic Tomato Soup', { ctxKind: 'scalar' })
  await basil.setField('Tomato Soup', 'cuisine', 'French', { ctxKind: 'scalar' })
  await basil.setField('Tomato Soup', 'servings', 4, { ctxKind: 'scalar' })
  await basil.setField('Tomato Soup', 'prepTime', 35, { ctxKind: 'scalar' })
  for (const ing of ['Tomato', 'Garlic', 'Olive Oil', 'Saffron']) {
    await basil.addMember('Tomato Soup', 'hasIngredient', { ref: ing }, { ctxKind: 'set' })
  }
  await basil.setField('Tomato Soup', 'tags', ['soup', 'starter']) // host key: Markdown face only (§5.6)
  const basilBody =
    'Simmer crushed [[Tomato]] with [[Garlic]] in [[Olive Oil]].\n\nBlend until smooth, season, and serve hot.'
  await basil.setBody('Tomato Soup', draft, basilBody) // revises his own converged draft

  // Clove bakes, and also touches Basil's note (cross-agent edit): the
  // concurrent AddMember lands in the same OR-set and UNIONS (§5.1, I5).
  say('clove', 'drafting "Garlic Bread"; also adds [[Basil]] to Tomato Soup (concurrent OR-set add)')
  await clove.addMember('Garlic Bread', 'type', { ref: 'Recipe' })
  await clove.setField('Garlic Bread', 'title', 'Golden Garlic Bread', { ctxKind: 'scalar' })
  await clove.setField('Garlic Bread', 'prepTime', 10, { ctxKind: 'scalar' })
  await clove.setField('Garlic Bread', 'difficulty', 'easy', { ctxKind: 'scalar' })
  for (const ing of ['Garlic', 'Baguette', 'Olive Oil']) {
    await clove.addMember('Garlic Bread', 'hasIngredient', { ref: ing }, { ctxKind: 'set' })
  }
  await clove.setBody('Garlic Bread', null, 'Split the [[Baguette]], butter generously, add [[Garlic]].\n\nBake until golden.')
  await clove.addMember('Tomato Soup', 'hasIngredient', { ref: 'Basil' }, { ctxKind: 'set' })
  await clove.addMember('Tomato Soup', 'pairsWith', { ref: 'Garlic Bread' }, { ctxKind: 'set' })

  // Dill cooks mains, stocks the pantry (clearing most dangling links when
  // the session heals), and CONCURRENTLY disagrees with Basil twice:
  //   - servings: a second LWW write to the same register (§5.4 clobber)
  //   - the body: a second revision citing the same base (§6 conflict)
  say('dill', 'drafting "Ratatouille" and the pantry (Tomato, Garlic, Basil, …)')
  await dill.addMember('Ratatouille', 'type', { ref: 'Recipe' })
  await dill.setField('Ratatouille', 'title', 'Ratatouille', { ctxKind: 'scalar' })
  await dill.setField('Ratatouille', 'cuisine', 'French', { ctxKind: 'scalar' })
  await dill.setField('Ratatouille', 'servings', 6, { ctxKind: 'scalar' })
  for (const ing of ['Tomato', 'Zucchini', 'Eggplant', 'Olive Oil', 'Herbes de Provence']) {
    await dill.addMember('Ratatouille', 'hasIngredient', { ref: ing }, { ctxKind: 'set' })
  }
  await dill.setBody('Ratatouille', null, 'Slice [[Tomato]], [[Zucchini]] and [[Eggplant]] thin; layer; bake slow.')
  for (const [ing, note] of [
    ['Tomato', 'Sweetest in late summer.'],
    ['Garlic', 'The backbone of everything.'],
    ['Basil', 'Tear it, never chop it.'],
    ['Olive Oil', 'Use the good bottle.'],
    ['Baguette', 'Day-old works best.'],
    ['Zucchini', 'Salt it first.'],
    ['Eggplant', 'Do not skip the salting.']
  ]) {
    await dill.addMember(ing, 'type', { ref: 'Ingredient' })
    await dill.setField(ing, 'comment', note, { ctxKind: 'scalar' })
  }
  say('dill', 'ALSO sets Tomato Soup servings to 6 and rewrites its body — concurrent with Basil')
  await dill.setField('Tomato Soup', 'servings', 6, { ctxKind: 'scalar' })
  const dillBody = 'Roast the [[Tomato]] halves first — always.\n\nThen simmer with [[Garlic]] and blend.'
  await dill.setBody('Tomato Soup', draft, dillBody) // cites the SAME base as Basil's revision (§6)

  // ---- phase 3: the session heals — every disagreement is visible ----------
  console.log('\n--- the agents reconnect: merge, audit, converge ---')
  offline = mesh(agents)
  await converge(agents)

  const soupIngredients = await nova.val(K.nField('Tomato Soup', 'hasIngredient'))
  say('all', `Tomato Soup hasIngredient UNIONED across writers: ${Object.values(soupIngredients.els).map((e) => e.v.ref).sort().join(', ')}`)
  const servings = await nova.val(K.nField('Tomato Soup', 'servings'))
  say('all', `Tomato Soup servings: LWW register resolved to ${servings.reg.values[0]} (deterministic linearization, §5.1)`)
  const clobbers = []
  for await (const { key } of nova.scan('flag/clobber/')) clobbers.push(key)
  say('all', `cross-writer overwrites are NOT silent: ${clobbers.length} flag/clobber record(s) (§5.4, I4)`)
  const conflicts = []
  for await (const { key, value } of nova.scan('flag/conflict/')) conflicts.push({ key, value })
  say('all', `body conflict detected and BOTH revisions kept: ${conflicts.length} flag/conflict record(s) (§6)`)
  const dangling = []
  for await (const { key, value } of nova.scan('flag/dangling/')) dangling.push(`${key.split('/')[2]} (${value.count} ref)`)
  say('all', `dangling wiki-links after the pantry landed: ${dangling.join(', ')} (§7)`)

  // ---- phase 4: Dill drains the queue (editorial pass) ---------------------
  console.log('\n--- editorial pass: Dill resolves what the flags surfaced ---')
  const keep = revHash(draft, basilBody)
  const supersede = revHash(draft, dillBody)
  const merged =
    'Roast the [[Tomato]] halves first — always.\n\nThen simmer with [[Garlic]] in [[Olive Oil]], blend until smooth, season, and serve hot.'
  say('dill', 'ResolveConflict on Tomato Soup: keep Basil\'s revision, supersede mine, append the merged text (§6)')
  await dill.append('resolve-conflict', { s: 'Tomato Soup', keep, supersede: [supersede], text: merged })
  say('dill', 'saffron in a rustic soup? removing it (RemMember cites every observed tag, §5.3)')
  await dill.remMember('Tomato Soup', 'hasIngredient', { ref: 'Saffron' }, { ctxKind: 'set' })
  say('dill', "tightening Clove's prepTime on Garlic Bread 10 → 12 (audited via flag/clobber)")
  await dill.setField('Garlic Bread', 'prepTime', 12, { ctxKind: 'scalar' })
  await converge(agents)

  const openConflicts = []
  for await (const { key } of nova.scan('flag/conflict/')) openConflicts.push(key)
  say('all', `flag/conflict drained by the ResolveConflict op: ${openConflicts.length} left`)
  const stillDangling = []
  for await (const { key } of nova.scan('flag/dangling/')) stillDangling.push(key.split('/')[2])
  say('all', `still dangling (left as a TODO for the next session): ${stillDangling.join(', ') || 'none'}`)

  // ---- phase 5: the human operator dumps the session -----------------------
  console.log('\n--- session dump: the knowledge graph as readable faces ---')
  const vaultDir = join(OUT, 'vault')
  const rdfDir = join(OUT, 'rdf')
  const report = await materialize(nova, vaultDir)
  if (report.pendingIngest.length > 0 || report.unsafe.length > 0) {
    throw new Error(
      `out/ has hand-edited or unsafe files (${[...report.pendingIngest, ...report.unsafe.map((u) => u.subject)].join(', ')}); ` +
        'out/ is generated — revert it and re-run'
    )
  }
  const ttl = await exportTurtle(nova, rdfDir, { roundtrip: true })
  say('nova', `materialized ${report.written.length + report.unchanged.length} files to ${relative(process.cwd(), vaultDir)}`)
  say('nova', `exported ${ttl.schema.triples} schema + ${ttl.data.triples} data triples to ${relative(process.cwd(), rdfDir)}`)

  console.log(`
=== what just happened ===
We told four agents to write a recipe book from scratch. They negotiated an
ontology, wrote concurrently while disconnected, disagreed, merged, and
audited every disagreement — all as ops in one shared log. That knowledge
graph is now represented as the Markdown files under out/vault/ (open the
folder in Obsidian) and as RDF under out/rdf/ (schema.ttl + data.ttl).
The op log stays the source of truth; out/ is a session dump a human can read.
`)

  offline() // destroy the replication streams before closing
  for (const v of agents) await v.close()
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
